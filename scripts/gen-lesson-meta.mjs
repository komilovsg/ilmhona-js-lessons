// Generates lib/lesson-meta.generated.ts from content/lessons/ru/*.html:
// AVAILABLE (slugs that have a fragment) and LESSON_META (slug -> task id -> level).
// Lesson slug = file name without the numeric prefix and extension (01-functions.html -> functions).
import fs from 'node:fs';

const dir = new URL('../content/lessons/ru/', import.meta.url);
const meta = {};
for (const f of fs.readdirSync(dir).filter((f) => /^\d{2}-.+\.html$/.test(f)).sort()) {
  const slug = f.replace(/^\d+-/, '').replace(/\.html$/, '');
  const html = fs.readFileSync(new URL(f, dir), 'utf8');
  const tasks = {};
  for (const m of html.matchAll(/<article class="task"[^>]*\sid="([^"]+)"[\s\S]*?<\/header>/g)) {
    tasks[m[1]] = (m[0].match(/class="level (easy|mid|hard)"/)?.[1] ?? 'mid')[0];
  }
  meta[slug] = tasks;
}

const body = Object.entries(meta)
  .map(([slug, tasks]) => `  '${slug}': {\n${Object.entries(tasks).map(([id, l]) => `    '${id}': '${l}',`).join('\n')}\n  },`)
  .join('\n');
const out = `// AUTO-GENERATED by scripts/gen-lesson-meta.mjs from content/lessons/ru. Do not edit.
/** Slugs of lessons that have content/lessons/ru/NN-slug.html, in file (= course) order. */
export const AVAILABLE = [${Object.keys(meta).map((s) => `'${s}'`).join(', ')}] as const;

export type LessonMeta = Record<string, Record<string, 'e' | 'm' | 'h'>>;

export const LESSON_META: LessonMeta = {
${body}
};
`;
fs.writeFileSync(new URL('../lib/lesson-meta.generated.ts', import.meta.url), out);
console.log('lesson meta generated:', Object.keys(meta).join(', '));
