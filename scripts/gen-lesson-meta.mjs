// Generates lib/lesson-meta.generated.ts from the lesson fragments:
//   content/lessons/ru/*.html              -> AVAILABLE, LESSON_META (slug -> task id -> level)
//   content/vibe-coding/lessons/ru/*.html  -> VC_AVAILABLE, VC_LESSON_META (progress key `vc-<slug>` -> task id -> level)
// Lesson slug = file name without the numeric prefix and extension (01-functions.html -> functions).
import fs from 'node:fs';

function scan(dirUrl, keyPrefix = '') {
  const dir = new URL(dirUrl, import.meta.url);
  const meta = {};
  for (const f of fs.readdirSync(dir).filter((f) => /^\d{2}-.+\.html$/.test(f)).sort()) {
    const slug = f.replace(/^\d+-/, '').replace(/\.html$/, '');
    const html = fs.readFileSync(new URL(f, dir), 'utf8');
    const tasks = {};
    for (const m of html.matchAll(/<article class="task"[^>]*\sid="([^"]+)"[\s\S]*?<\/header>/g)) {
      tasks[m[1]] = (m[0].match(/class="level (easy|mid|hard)"/)?.[1] ?? 'mid')[0];
    }
    meta[keyPrefix + slug] = tasks;
  }
  return meta;
}

const render = (meta) =>
  Object.entries(meta)
    .map(([slug, tasks]) => `  '${slug}': {\n${Object.entries(tasks).map(([id, l]) => `    '${id}': '${l}',`).join('\n')}\n  },`)
    .join('\n');

const meta = scan('../content/lessons/ru/');
const vcMeta = scan('../content/vibe-coding/lessons/ru/', 'vc-');
const vcSlugs = Object.keys(vcMeta).map((k) => k.slice(3));

const out = `// AUTO-GENERATED by scripts/gen-lesson-meta.mjs from content/lessons/ru. Do not edit.
/** Slugs of lessons that have content/lessons/ru/NN-slug.html, in file (= course) order. */
export const AVAILABLE = [${Object.keys(meta).map((s) => `'${s}'`).join(', ')}] as const;

export type LessonMeta = Record<string, Record<string, 'e' | 'm' | 'h'>>;

export const LESSON_META: LessonMeta = {
${render(meta)}
};

/** Vibe Coding: slugs with content/vibe-coding/lessons/ru/NN-slug.html (plain slugs, course order). */
export const VC_AVAILABLE = ${vcSlugs.length ? `[${vcSlugs.map((s) => `'${s}'`).join(', ')}] as const` : '[] as readonly string[]'};

/** Vibe Coding task levels, keyed by progress key \`vc-<slug>\`. */
export const VC_LESSON_META: LessonMeta = {
${render(vcMeta)}
};
`;
fs.writeFileSync(new URL('../lib/lesson-meta.generated.ts', import.meta.url), out);
console.log('lesson meta generated:', Object.keys(meta).join(', '), '| vibe-coding:', vcSlugs.join(', ') || '-');
