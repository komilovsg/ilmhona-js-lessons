/** Modules with their lesson ranges derived from `course`. */
export const modules: CourseModule[] = moduleTitles.map((m) => {
  const nums = course.filter((c) => c.module === m.id).map((c) => c.num);
  return { ...m, from: Math.min(...nums), to: Math.max(...nums) };
});

/** File name of the lesson fragment in content/lessons/<locale>/. */
export const lessonFile = (c: Pick<CourseEntry, 'num' | 'slug'>) => `${String(c.num).padStart(2, '0')}-${c.slug}.html`;

/** A lesson is available iff its fragment file exists (list generated at build by scripts/gen-lesson-meta.mjs). */
export const isAvailable = (c: CourseEntry) => (AVAILABLE as readonly string[]).includes(c.slug);

export const availableCourse = (): CourseEntry[] => course.filter(isAvailable);

export const getCourseEntry = (slug: string) => course.find((c) => c.slug === slug);
